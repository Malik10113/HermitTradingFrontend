@dataclass(frozen=True)
class Settings:
    host: str = os.environ.get("HTF_HOST", "127.0.0.1")
    port: int = int(os.environ.get("HTF_PORT", "8787"))
    app_token: str | None = os.environ.get("HTF_APP_TOKEN")
    max_grid_runs: int = 50
    hard_max_grid_runs: int = 200
    book_staleness_s: int = 60
    max_depth_levels: int = 10
    concurrency: int = 1


SETTINGS = Settings()


def ensure_dirs() -> None:
    for path in (
        VAR_DIR,
        BARS_DIR,
        CATALOG_DIR,
        LIFECYCLE_PATH.parent,
        SETTLEMENT_PATH.parent,
        INDEX_PATH.parent,
        RUNS_DIR,
        LOGS_DIR,
        SIGNAL_CACHE_DIR,
    ):
        path.mkdir(parents=True, exist_ok=True)


def code_version() -> str:
    """Git SHA of the running checkout, or ``"unknown"`` outside a repo."""
    override = os.environ.get("HTF_CODE_VERSION")
    if override:
        return override
    try:
        out = subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            timeout=5,
        )
        return out.stdout.strip()
    except Exception:  # noqa: BLE001 - provenance must never break the app
        return "unknown"


def nautilus_version() -> str:
    try:
        import nautilus_trader

        return nautilus_trader.__version__
    except Exception:  # noqa: BLE001
        return "not installed"
