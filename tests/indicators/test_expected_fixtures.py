"""Checked-in expected series for EMA, RSI and MACD.

``fixtures/expected_series.json`` is generated by
``tests/indicators/fixtures/generate_expected.py`` from the first-principles
reference implementations — never by copying NautilusTrader output.  It pins
the values so an adapter or Nautilus upgrade shows up as an explicit diff.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from backend.indicators import compute_series
from tests.indicators.assertions import assert_values_close
from tests.indicators.fixtures.bars import make_bars
from tests.indicators.fixtures.generate_expected import CASES, build_payload

FIXTURE = Path(__file__).parent / "fixtures" / "expected_series.json"


def load_expected() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_checked_in_fixture_is_current() -> None:
    """The JSON on disk equals what the reference implementations produce."""
    assert load_expected() == build_payload()


def test_checked_in_fixture_covers_the_bars() -> None:
    payload = load_expected()
    assert payload["bar_count"] == len(make_bars())
    assert set(payload["indicators"]) == set(CASES)


@pytest.mark.parametrize("indicator_id", sorted(CASES))
def test_computation_matches_checked_in_expected_series(indicator_id: str) -> None:
    payload = load_expected()
    case = payload["indicators"][indicator_id]
    expected = case["series"]

    series = compute_series(
        make_bars(),
        [
            {
                "instance_id": indicator_id,
                "type": indicator_id,
                "params": case["params"],
            }
        ],
    )[indicator_id]

    assert set(series) == set(expected)
    for key, expected_values in expected.items():
        assert_values_close(
            series[key], expected_values, context=f"{indicator_id}.{key}"
        )


def test_expected_series_contains_nulls_and_floats() -> None:
    payload = load_expected()
    values = payload["indicators"]["ema"]["series"]["value"]
    assert values[0] is None
    assert values[19] is not None
    assert all(value is None for value in values[:19])
    assert set(payload["indicators"]["macd"]["series"]) == {
        "value",
        "signal",
        "histogram",
    }
